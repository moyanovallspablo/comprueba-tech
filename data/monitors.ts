export const DATA_SNAPSHOT = "2026-10";

function monthsBetween(from: string, to: string): number {
  const [y1, m1] = from.split("-").map(Number);
  const [y2, m2] = to.split("-").map(Number);
  return Math.max(0, (y2 - y1) * 12 + (m2 - m1));
}

